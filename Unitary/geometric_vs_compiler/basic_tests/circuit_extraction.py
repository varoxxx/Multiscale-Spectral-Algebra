# ============================================================
# Helper: reconstruct unitary from a circuit description
# ============================================================

def apply_circuit(n_qubits, layers):
    """
    layers: list of dicts, each layer has:
        {
          "single": [(q, U1), ...],
          "two":    [((i,j), U2), ...]
        }
    Returns full unitary U_recon.
    """
    N = 2**n_qubits
    U = cp.eye(N, dtype=cp.complex128)

    for layer in layers:
        # single-qubit gates
        for q, U1 in layer.get("single", []):
            U_full = kron_on_qubits(U1, [q], n_qubits)
            U = U_full @ U
        # two-qubit gates
        for (i, j), U2 in layer.get("two", []):
            U_full = kron_on_qubits(U2, [i, j], n_qubits)
            U = U_full @ U

    # re-unitarize to clean drift
    Q, _ = cp.linalg.qr(U)
    return Q

