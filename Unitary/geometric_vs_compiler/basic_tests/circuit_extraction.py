# Very simple circuit extraction via local SVD projections
# ============================================================

def extract_local_two_qubit(U, n_qubits, edge):
    """
    Extract an approximate 2-qubit gate acting on 'edge' from full U
    using an SVD-based projection similar to your tensor factors.
    """
    i, j = edge
    N = 2**n_qubits
    d_local = 4  # 2 qubits
    d_rest = N // d_local

    # reshape U into (local, rest) x (local, rest)
    U4 = U.reshape(d_local, d_rest, d_local, d_rest)
    # permute to (local_in, local_out, rest_in, rest_out)
    U_perm = cp.transpose(U4, (0, 2, 1, 3))
    M = U_perm.reshape(d_local * d_local, d_rest * d_rest)

    u, s, vh = cp.linalg.svd(M, full_matrices=False)
    a = u[:, 0] * cp.sqrt(s[0])
    A_raw = a.reshape(d_local, d_local)
    Q_local, _ = cp.linalg.qr(A_raw)
    return Q_local

def extract_local_single_qubit(U, n_qubits, q):
    """
    Extract an approximate 1-qubit gate on qubit q from full U
    using a similar projection idea.
    """
    N = 2**n_qubits
    d_local = 2
    d_rest = N // d_local

    U4 = U.reshape(d_local, d_rest, d_local, d_rest)
    U_perm = cp.transpose(U4, (0, 2, 1, 3))
    M = U_perm.reshape(d_local * d_local, d_rest * d_rest)

    u, s, vh = cp.linalg.svd(M, full_matrices=False)
    a = u[:, 0] * cp.sqrt(s[0])
    A_raw = a.reshape(d_local, d_local)
    Q_local, _ = cp.linalg.qr(A_raw)
    return Q_local

def extract_hardware_circuit(U_target, n_qubits, depth):
    """
    Very simple, local-projection-based circuit extraction:
    for each layer, extract single-qubit and two-qubit gates
    that best approximate U_target in a greedy way.
    """
    layers = []
    edges = make_linear_chain_edges(n_qubits)

    U_work = U_target.copy()

    for d in range(depth):
        layer = {"single": [], "two": []}

        # extract single-qubit gates
        for q in range(n_qubits):
            U1 = extract_local_single_qubit(U_work, n_qubits, q)
            layer["single"].append((q, U1))
            U_full = kron_on_qubits(U1, [q], n_qubits)
            U_work = cp.linalg.solve(U_full, U_work)

        # extract two-qubit gates
        for (i, j) in edges:
            U2 = extract_local_two_qubit(U_work, n_qubits, (i, j))
            layer["two"].append(((i, j), U2))
            U_full = kron_on_qubits(U2, [i, j], n_qubits)
            U_work = cp.linalg.solve(U_full, U_work)

        layers.append(layer)

    return layers

