# Advanced Reconstruction Audit (Multi‑Pass Extraction)
# ============================================================

def advanced_reconstruction_audit(U_target, U_recon, name="advanced_extract"):
    """
    Performs a deep validation of the reconstructed unitary from the
    multi‑pass circuit extraction algorithm. This is designed for public
    release and provides multiple independent checks to confirm that the
    result is real, stable, and behaves as expected.

    Checks performed:
      1) Frobenius distance between U_target and U_recon
      2) Direct unitarity (U_recon U_recon† = I)
      3) Column orthonormality
      4) Determinant magnitude (|det(U_recon)| ≈ 1)
      5) Eigenvalues on the unit circle
      6) Hilbert‑Schmidt fidelity between U_target and U_recon
      7) Residual norm ||R − I||_F where R = U_target U_recon†
      8) Save matrices for external verification
    """

    Ut = cp.asnumpy(U_target)
    Ur = cp.asnumpy(U_recon)
    N = Ut.shape[0]

    print(f"\n=== ADVANCED RECONSTRUCTION AUDIT: {name} ===")

    # 1. Frobenius distance
    frob = np.linalg.norm(Ut - Ur)
    print(f"Frobenius distance ||U_target - U_recon||_F = {frob:.12e}")

    # 2. Direct unitarity check
    direct = np.allclose(Ur @ Ur.conj().T, np.eye(N), atol=1e-12)
    print(f"Direct unitarity (U_recon U_recon† = I): {direct}")

    # 3. Column orthonormality
    cols = Ur.T
    norms = [np.linalg.norm(c) for c in cols]
    orthonormal = all(abs(n - 1) < 1e-12 for n in norms)
    print(f"Column orthonormality: {orthonormal}")

    # 4. Determinant magnitude
    det_mag = abs(np.linalg.det(Ur))
    det_ok = abs(det_mag - 1) < 1e-12
    print(f"Determinant magnitude: {det_mag:.12f} (ok={det_ok})")

    # 5. Eigenvalues on the unit circle
    eigs = np.linalg.eigvals(Ur)
    eig_ok = all(abs(abs(ev) - 1) < 1e-12 for ev in eigs)
    print(f"Eigenvalues on unit circle: {eig_ok}")

    # 6. Hilbert‑Schmidt fidelity
    hs_num = np.trace(Ut.conj().T @ Ur)
    hs_den = np.sqrt(np.trace(Ut.conj().T @ Ut) * np.trace(Ur.conj().T @ Ur))
    fidelity = abs(hs_num / hs_den)
    print(f"Hilbert-Schmidt fidelity: {fidelity:.12f}")

    # 7. Residual norm ||R − I||_F
    R = Ut @ Ur.conj().T
    R_diff = R - np.eye(N)
    residual_norm = np.linalg.norm(R_diff)
    print(f"Residual norm ||U_target U_recon† − I||_F = {residual_norm:.12e}")

    # 8. Save matrices for external verification
    np.save(f"audit_U_target_{name}.npy", Ut)
    np.save(f"audit_U_recon_{name}.npy", Ur)
    np.save(f"audit_residual_{name}.npy", R)

    print("Advanced audit complete. Matrices saved for external verification.\n")

