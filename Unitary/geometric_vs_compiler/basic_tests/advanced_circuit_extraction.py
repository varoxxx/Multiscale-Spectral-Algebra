def advanced_circuit_extraction_test(n_qubits=4, depth=6, passes=3):
    N = 2**n_qubits

    print("\n======================================")
    print(f"Advanced Circuit Extraction Test (n_qubits={n_qubits}, depth={depth}, passes={passes})")
    print("======================================")

    # target unitary from hardware-efficient manifold
