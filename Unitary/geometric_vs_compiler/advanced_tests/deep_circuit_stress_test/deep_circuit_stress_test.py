import numpy as np
import cupy as cp

from qiskit import QuantumCircuit
from qiskit.quantum_info import Operator, Statevector

# Your modules
from module_geometric_optimizer import GeometricOptimizer
from module_fidelity_objective import FidelityObjective


# ============================================================
# Utility Metrics (copied exactly from your structured tests)
# ============================================================

def frobenius_diff(A, B):
    return float(cp.linalg.norm(A - B))

def delta_norm(A, B):
    return float(cp.linalg.norm(A - B))

def physical_state_fidelity(Ua, Ub, n_qubits, trials=10):
    dim = 2**n_qubits
    total = 0.0
    for _ in range(trials):
        psi = cp.random.randn(dim) + 1j * cp.random.randn(dim)
        psi = psi / cp.linalg.norm(psi)
        out_a = Ua @ psi
        out_b = Ub @ psi
        fid = FidelityObjective.state_fidelity(out_a, out_b, n_qubits)
        total += fid
    return total / trials

def functional_circuit_fidelity(Ua, Ub, n_qubits):
    qc_a = QuantumCircuit(n_qubits)
    qc_b = QuantumCircuit(n_qubits)
    qc_a.unitary(cp.asnumpy(Ua), range(n_qubits))
    qc_b.unitary(cp.asnumpy(Ub), range(n_qubits))
    sv_a = Statevector.from_instruction(qc_a)
    sv_b = Statevector.from_instruction(qc_b)
    probs_a = sv_a.probabilities()
    probs_b = sv_b.probabilities()
    return float(np.sum(np.sqrt(probs_a * probs_b)))

def phase_normalized_diff(A, B):
    A_cpu = cp.asnumpy(A)
    B_cpu = cp.asnumpy(B)
    num = np.vdot(B_cpu.flatten(), A_cpu.flatten())
    phase = num / abs(num + 1e-18)
    B_aligned = phase * B_cpu
    diff = A_cpu - B_aligned
    frob = np.linalg.norm(diff)
    delta = frob
    return frob, delta


# ============================================================
# Deep Circuit Layer Builders
# ============================================================

def random_single_qubit_layer(num_qubits):
    qc = QuantumCircuit(num_qubits)
    for q in range(num_qubits):
        qc.rx(np.random.uniform(0, 2*np.pi), q)
        qc.ry(np.random.uniform(0, 2*np.pi), q)
        qc.rz(np.random.uniform(0, 2*np.pi), q)
    return qc

def entangling_layer_cnot_ring(num_qubits):
    qc = QuantumCircuit(num_qubits)
    for q in range(num_qubits):
        qc.cx(q, (q+1) % num_qubits)
    return qc

def diagonal_phase_layer(num_qubits):
    qc = QuantumCircuit(num_qubits)
    for q in range(num_qubits):
        qc.rz(np.random.uniform(0, 2*np.pi), q)
    return qc

def entangling_layer_nearest_neighbor(num_qubits):
    qc = QuantumCircuit(num_qubits)
    for q in range(num_qubits - 1):
        qc.cx(q, q+1)
    return qc

def qft_layer(num_qubits):
    qc = QuantumCircuit(num_qubits)
    for j in range(num_qubits):
        qc.h(j)
        for k in range(j+1, num_qubits):
            qc.cp(np.pi / (2**(k-j)), k, j)
    for i in range(num_qubits // 2):
        qc.swap(i, num_qubits - i - 1)
    return qc


# ============================================================
# Build Deep Stress Circuit
# ============================================================

def build_deep_stress_circuit(num_qubits=4, depth=10):
    qc = QuantumCircuit(num_qubits)
    for d in range(depth):
        qc.compose(random_single_qubit_layer(num_qubits), inplace=True)
        qc.compose(entangling_layer_cnot_ring(num_qubits), inplace=True)
        qc.compose(diagonal_phase_layer(num_qubits), inplace=True)
        qc.compose(entangling_layer_nearest_neighbor(num_qubits), inplace=True)
        if d % 3 == 0:
            qc.compose(qft_layer(num_qubits), inplace=True)
    return qc


# ============================================================
# Convert Circuit to Unitary (GPU)
# ============================================================

def circuit_to_unitary_gpu(qc):
    U_cpu = Operator(qc).data
    return cp.asarray(U_cpu, dtype=cp.complex128)


# ============================================================
# Geometric Collapse (Your Optimizer)
# ============================================================

def geometric_collapse_to_target(U_target, num_qubits):
    N = 2**num_qubits
    U_init = cp.eye(N, dtype=cp.complex128)
    U_final, _ = GeometricOptimizer.optimize(
        U_init,
        U_target,
        num_qubits,
        steps=300,
        frac_ext=0.8,
        lam_reg=0.1,
        step_scale=0.1,
        verbose=False
    )
    return U_final


# ============================================================
# Run Single Stress Test
# ============================================================

def run_deep_circuit_stress_test(num_qubits=4, depth=10, label="stress"):
    print(f"\n=== Deep Circuit Stress Test: {label} ===")
    print(f"num_qubits={num_qubits}, depth={depth}")

    qc = build_deep_stress_circuit(num_qubits, depth)
    U_target = circuit_to_unitary_gpu(qc)
    U_geo = geometric_collapse_to_target(U_target, num_qubits)

    fid = FidelityObjective.operator_fidelity(U_geo, U_target)
    frob = frobenius_diff(U_geo, U_target)
    delta = delta_norm(U_geo, U_target)
    phys = physical_state_fidelity(U_geo, U_target, num_qubits)
    func = functional_circuit_fidelity(U_geo, U_target, num_qubits)

    print(f"Operator fidelity:        {fid:.6f}")
    print(f"Frobenius distance:       {frob:.6f}")
    print(f"Delta-norm:               {delta:.6f}")
    print(f"Physical fidelity:        {phys:.6f}")
    print(f"Functional fidelity:      {func:.6f}")

    np.save(f"{label}_U_target.npy", cp.asnumpy(U_target))
    np.save(f"{label}_U_geo.npy", cp.asnumpy(U_geo))

    return {
        "label": label,
        "num_qubits": num_qubits,
        "depth": depth,
        "operator_fidelity": float(fid),
        "frob_dist": float(frob),
        "delta_norm": float(delta),
        "physical_fidelity": float(phys),
        "functional_fidelity": float(func),
    }


# ============================================================
# Batch Suite
# ============================================================

def run_deep_circuit_stress_suite():
    configs = [
        {"num_qubits": 3, "depth": 8,  "label": "stress_3q_d8"},
        {"num_qubits": 4, "depth": 10, "label": "stress_4q_d10"},
        {"num_qubits": 5, "depth": 12, "label": "stress_5q_d12"},
    ]
    results = []
    for cfg in configs:
        results.append(run_deep_circuit_stress_test(**cfg))
    return results


